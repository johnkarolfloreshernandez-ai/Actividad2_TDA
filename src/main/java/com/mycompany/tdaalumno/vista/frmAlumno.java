    private void btnProcesarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcesarActionPerformed
        
        try {

            String nombre = txtNombre.getText();

            int edad = Integer.parseInt(txtEdad.getText());

            double calificacion =
                    Double.parseDouble(txtCalificacion.getText());

            // Creamos el objeto Alumno
            alumno = new Alumno(
                    nombre,
                    edad,
                    calificacion
            );

            // Mostramos los resultados
            txtResultadoo.setText(
                    alumno.mostrarDatos()
                    + "\n\n"
                    + alumno.obtenerMensaje()
                    + "\n"
                    + "Puntos para llegar a 10: "
                    + alumno.puntosParaDiez()
                    + "\n"
                    + "Recursividad: "
                    + alumno.contarRegresivo(5)
            );

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ingresa correctamente la edad y la calificación.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    
    }//GEN-LAST:event_btnProcesarActionPerformed

